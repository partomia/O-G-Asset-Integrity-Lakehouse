GLYPH_W, GLYPH_H = 5, 8          # 8 rows: ',' uses the descender row
SCALE = 2                        # every font pixel is SCALE x SCALE image pixels
CELL_W = (GLYPH_W + 1) * SCALE   # one blank column between characters
LINE_H = (GLYPH_H + 3) * SCALE   # three blank rows between lines


def glyph(ch: str) -> list[list[int]]:
    """rows x cols of 0/1 at font resolution; unknown characters render as '?'."""
    cols = COLUMNS.get(ch.upper(), COLUMNS["?"])
    return [[(cols[c] >> r) & 1 for c in range(GLYPH_W)] for r in range(GLYPH_H)]


def printable(text: str) -> str:
    """What the font can show: upper case, unknown characters as '?'."""
    return "".join(c if c in COLUMNS else "?" for c in text.upper())


def draw_text(pixels: bytearray, width: int, x: int, y: int, text: str, ink: int = 0) -> None:
    """Draw text onto an 8-bit grayscale buffer (row-major, `width` wide) at pixel (x, y)."""
    height = len(pixels) // width
    for i, ch in enumerate(printable(text)):
        g = glyph(ch)
        x0 = x + i * CELL_W
        for r in range(GLYPH_H):
            for c in range(GLYPH_W):
                if g[r][c]:
                    for dy in range(SCALE):
                        yy = y + r * SCALE + dy
                        if 0 <= yy < height:
                            base = yy * width
                            for dx in range(SCALE):
                                xx = x0 + c * SCALE + dx
                                if 0 <= xx < width:
                                    pixels[base + xx] = ink
